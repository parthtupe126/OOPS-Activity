#include <iostream>
using namespace std;

int main() {
  // Variable to store integer roll number
  int roll = 101;

  // Variable to store single character grade
  char grade = 'A';

  // Variable to store decimal fee amount
  float fee = 12500.50;

  // Display roll number
  cout << "Roll No: " << roll << endl;

  // Display grade
  cout << "Grade: " << grade << endl;

  // Display fee amount
  cout << "Fee: " << fee << endl;

  // End program successfully
  return 0;
}