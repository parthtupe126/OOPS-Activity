#include <iostream>
using namespace std;

int main() {
  // Variable to store student marks
  int marks = 45;

  // Condition: check if marks are 40 or greater
  if (marks >= 40) {
    // Runs if marks >= 40
    cout << "Pass";
  } else {
    // Runs if condition is false
    cout << "Fail";
  }

  return 0;
}